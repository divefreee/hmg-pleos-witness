package io.pleos.snapreport.domain.model

/**
 * 안전신문고 자동차·교통위반 주요 신고 유형 코드
 */
enum class TrafficViolationType(
    val code: String,
    val titleKo: String,
    val legalBasis: String
) {
    ILLEGAL_CUT_IN_NO_SIGNAL(
        code = "MOIS-TRF-101",
        titleKo = "진로변경 방법 위반 (방향지시등 미점등 끼어들기)",
        legalBasis = "도로교통법 제19조 제3항 및 제38조 제1항(제차 신호 조작 불이행)"
    ),
    SIGNAL_VIOLATION(
        code = "MOIS-TRF-102",
        titleKo = "신호 또는 지시 위반",
        legalBasis = "도로교통법 제5조(신호 또는 지시에 따를 의무)"
    ),
    DESIGNATED_LANE_VIOLATION(
        code = "MOIS-TRF-103",
        titleKo = "지정차로 통행 위반 (고속도로 앞지르기 차로 등)",
        legalBasis = "도로교통법 제60조 제1항(고속도로 등에서의 앞지르기 방법)"
    ),
    RECKLESS_DRIVING(
        code = "MOIS-TRF-104",
        titleKo = "난폭·보복운전 및 급감속 위협",
        legalBasis = "도로교통법 제46조의3(난폭운전 금지)"
    ),
    UNSECURED_CARGO(
        code = "MOIS-TRF-105",
        titleKo = "적재물 추락방지 조치 위반",
        legalBasis = "도로교통법 제39조 제4항(승차 또는 적재의 방법과 제한)"
    )
}

/**
 * Pleos Vehicle SDK + FusedLocation SDK + NaviHelper SDK가 수집한 차량 센서/주행 맥락 스냅샷
 */
data class VehicleTelemetrySnapshot(
    val timestampIso: String,
    val latitude: Double,
    val longitude: Double,
    val bearingDeg: Float,
    val roadAddress: String,
    val roadNameAndLane: String,
    val speedLimitKmh: Int,
    val egoSpeedKmh: Int,
    val brakePedalPressed: Boolean,
    val suddenDecelerationG: Float,
    val parkingBrakeEngaged: Boolean,
    val egoTurnSignalState: String
)

/**
 * 빌트인 캠 2 + 온디바이스 비전 AI (Multi-frame Super-Resolution ANPR) 분석 결과
 */
data class EdgeAiVisionResult(
    val recognizedPlate: String,
    val plateConfidence: Float,
    val detectedViolation: TrafficViolationType,
    val targetTurnSignalDetected: Boolean,
    val clipFilePath: String,
    val superResPlateCropPath: String,
    val privacyMaskedObjectsCount: Int,
    val sha256IntegrityHash: String
)

/**
 * 행정안전부 안전신문고 Open API (제공 가정) 전송용 최종 공익신고 패키지
 */
data class SafetyReportDraft(
    val reportId: String,
    val telemetry: VehicleTelemetrySnapshot,
    val aiVision: EdgeAiVisionResult,
    val autoGeneratedTitle: String,
    val autoGeneratedBody: String,
    val status: ReportStatus = ReportStatus.READY_FOR_REVIEW,
    val moisReceiptNumber: String? = null,
    val assignedAgency: String? = null
)

enum class ReportStatus {
    CAPTURING_AND_ANALYZING,
    READY_FOR_REVIEW,
    SUBMITTING,
    SUBMITTED_COMPLETED
}
